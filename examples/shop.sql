drop schema if exists shop cascade;
create schema shop;

create table shop.customers (
  id uuid primary key,
  name text not null,
  email text,
  created_at timestamptz
);

create table shop.products (
  id uuid primary key,
  sku text not null unique,
  name text not null,
  price numeric(12, 2) not null
);

create table shop.orders (
  id uuid primary key,
  customer_id uuid not null references shop.customers (id),
  status text not null,
  placed_at timestamptz not null
);

create table shop.order_items (
  id bigint generated by default as identity primary key,
  order_id uuid not null references shop.orders (id) on delete cascade,
  product_id uuid not null references shop.products (id),
  quantity int not null,
  unit_price numeric(12, 2) not null,
  currency text
);
create index on shop.order_items (order_id);
